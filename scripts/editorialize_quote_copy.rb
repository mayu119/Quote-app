def flat(text)
  text.to_s.gsub(/\s+/, " ").strip
end

def lines(text)
  text.to_s.split(/\n+/).map(&:strip).reject(&:empty?)
end

def lead(text)
  lines(text).first || flat(text)
end

def follow(text)
  lines(text)[1]
end

def quoted(text)
  value = lead(text).to_s.gsub(/[。！？」]+$/, "")
  "「#{value}」"
end

def has_any?(text, *keywords)
  keywords.any? { |keyword| text.include?(keyword) }
end

