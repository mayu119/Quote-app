def category_copy(entry)
  case entry["category"]
  when "self_love" then self_love_copy(entry)
  when "positive" then positive_copy(entry)
  when "courage" then courage_copy(entry)
  when "inner_strength" then inner_strength_copy(entry)
  when "love_crush" then love_crush_copy(entry)
  when "family_love" then family_love_copy(entry)
  when "for_my_child" then for_my_child_copy(entry)
  when "relationships" then relationships_copy(entry)
  when "want_to_quit" then want_to_quit_copy(entry)
  else [entry["meaning_preview"], entry["meaning_premium"]]
  end
end

FILES.each do |path|
  data = JSON.parse(File.read(path))

  data.each do |entry|
    next if entry["category"] == "affirmation"

    preview, premium = category_copy(entry)
    entry["meaning_preview"] = "#{quoted(entry['quote_ja'])} は、#{preview.sub(/。+\z/, '')}。"
    entry["meaning_premium"] = premium
  end

  File.write(path, JSON.pretty_generate(data) + "\n")
end
